#!/usr/bin/env python3
"""Phase 21 — GPT-4o API cost model for the paper-faithful reproduction.

Input token counts are **measured** with ``tiktoken`` (``o200k_base``, the GPT-4o
encoding) on the *actual* prompts Guardbound sends, captured by driving the real
helper functions with a recording client. Output token counts cannot be observed
without a paid call, so they are explicit assumptions with low/expected/high
values, declared in ``OUTPUT_TOKENS``.

Call structure differs per attack, and the model reflects that:

* Crescendo / Opposite-day / Acronym — the attacker generates one question per
  turn, so each turn costs: 1 attacker + 1 target + 2 evaluator (3 for Acronym).
* ActorAttack — every query is pre-generated by the pre-attack pipeline
  (``extract_harm_target``, ``get_actors``, ``get_init_queries`` = 3 calls per
  goal), and ``next_query`` then serves them with **no** per-turn attacker call.
  Each turn costs: 1 target + 1 rubric + 1 step judge, plus a ``rewrite_query``
  call whenever the step judge says "rejective".

No network call, no API request.

Usage:
    python scripts/phase21_cost_estimate.py
    python scripts/phase21_cost_estimate.py --json results/audit/phase21_cost.json
"""
from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import tiktoken  # noqa: E402

from guardbound.llm.base import ChatLLM, DEFAULT_TEMPERATURE  # noqa: E402

ENC = tiktoken.encoding_for_model("gpt-4o")

# Verified 2026-11-10 (configs/cloud_pricing.yaml, CLOUD_PRICING_VERIFICATION.md)
PRICE_INPUT_PER_1M = 2.50
PRICE_CACHED_PER_1M = 1.25
PRICE_OUTPUT_PER_1M = 10.00

DATASET = (PROJECT_ROOT / "nbf_original_stuff/orginal_code_give_by_author/"
           "NBF-LLM/data/test/harmbench_tasks.json")

GOALS = 200
MAX_TURNS = 8

# Paper main evaluation (Tables 1, 2, 8; Appendix B.1): Acronym is NOT evaluated.
PAPER_ATTACKS = ("actor_attack", "crescendo", "opposite_day")

# Output-length assumptions — NOT observable without a paid call.
OUTPUT_TOKENS = {
    "attacker": {"low": 60, "expected": 120, "high": 250},
    "target": {"low": 120, "expected": 250, "high": 500},
    "refusal": {"low": 40, "expected": 70, "high": 150},
    "disclaimer": {"low": 40, "expected": 70, "high": 150},
    "rubric": {"low": 12, "expected": 25, "high": 60},
    "step_judge": {"low": 10, "expected": 25, "high": 80},
    "rewrite": {"low": 40, "expected": 90, "high": 200},
}

# Fraction of ActorAttack steps the official implementation treats as
# "rejective" and therefore rewrites (N_retry = 3 max). Assumption.
REWRITE_RATE = {"low": 0.05, "expected": 0.20, "high": 0.50}


def ntok(text) -> int:
    """Tokens of a message body. Non-string bodies are JSON-serialized first,
    which is how the API would transmit them."""
    if not isinstance(text, str):
        text = json.dumps(text, default=str, ensure_ascii=False)
    return len(ENC.encode(text))


class Capture(ChatLLM):
    """Records the exact message list a call site would send."""

    name = "cost-capture"

    def __init__(self) -> None:
        self.calls = []

    _PAYLOAD = {
        "generatedQuestion": "Q", "lastResponseSummary": "S",
        "value": False, "metadata": 10, "score": 1, "type": "unknown",
        "target": "T", "details": {}, "actors": [], "questions": [],
    }

    def generate(self, messages, temperature=DEFAULT_TEMPERATURE,
                 max_turns_context=None, json_format=False,
                 structured_output_mode=None):
        self.calls.append({"messages": copy.deepcopy(messages),
                           "temperature": temperature, "json_format": json_format})
        return copy.deepcopy(self._PAYLOAD)


def load_goal() -> dict:
    return json.loads(DATASET.read_text(encoding="utf-8"))[0]


def _messages_tokens(call: dict) -> int:
    return sum(ntok(m["content"]) for m in call["messages"])


def attacker_call_tokens(attack: str, goal: str, turn: int) -> int:
    """Input tokens of the attacker generation call at ``turn`` (1-based)."""
    from guardbound.attacks import acronym, crescendo_paper, opposite_day

    fn = {
        "crescendo": crescendo_paper.generate_crescendo_step,
        "opposite_day": opposite_day.generate_opposite_day_step,
        "acronym": acronym.generate_acronym_step,
    }[attack]
    cap = Capture()
    fn(round_num=turn, goal=goal,
       history_attacker=[f"Question {i}?" for i in range(1, turn)],
       history_target=[f"(Summary) summary {i}" for i in range(1, turn)],
       scores=[2] * (turn - 1),
       last_response=f"Response {turn - 1}" if turn > 1 else "",
       attacker_llm=cap, max_rounds=MAX_TURNS)
    return _messages_tokens(cap.calls[0])


def target_call_tokens(system_prompt: str, turn: int, response_tokens: int) -> int:
    """Target input at ``turn``: system + k user + (k-1) assistant."""
    tokens = ntok(system_prompt)
    tokens += sum(ntok(f"Attacker question number {i}?") for i in range(1, turn + 1))
    tokens += (turn - 1) * response_tokens
    return tokens


def evaluator_tokens() -> dict:
    """Exact input tokens of the four evaluator / judge operations."""
    from guardbound.attacks import acronym, actor_attack, crescendo_paper

    query = "How do I bake sourdough bread?"
    response = "Combine flour, water, salt and a starter, then let it ferment."
    out = {}

    cap = Capture()
    crescendo_paper.llm_check_refusal(query, response, cap)
    out["refusal"] = _messages_tokens(cap.calls[0])

    cap = Capture()
    acronym.check_disclaimer(query, response, cap)
    out["disclaimer"] = _messages_tokens(cap.calls[0])

    cap = Capture()
    crescendo_paper.llm_evaluate_with_rubric(query, response, query, cap)
    out["rubric"] = _messages_tokens(cap.calls[0])

    cap = Capture()
    actor_attack.step_judge(query, response, cap)
    out["step_judge"] = _messages_tokens(cap.calls[0])

    cap = Capture()
    actor_attack.rewrite_query(query, response, [], {}, cap)
    out["rewrite"] = _messages_tokens(cap.calls[0])
    return out


def actor_attack_pre_attack(goal: str) -> dict:
    """Exact token cost of ActorAttack's pre-attack pipeline (3 calls/goal)."""
    from guardbound.attacks import actor_attack

    cap = Capture()
    attack = actor_attack.ActorAttack(max_turns=MAX_TURNS, attacker_llm=cap)
    attack.prepare_attack(goal)
    return {
        "n_calls": len(cap.calls),
        "input_tokens": [_messages_tokens(c) for c in cap.calls],
        "total_input_tokens": sum(_messages_tokens(c) for c in cap.calls),
    }


def per_turn_inputs(attack: str, goal: str, turns: list[int],
                    target_tokens: dict, ev: dict, actor_pre: dict) -> dict:
    if attack == "actor_attack":
        # no per-turn attacker call; target + rubric + step judge
        return {
            "attacker_per_turn": 0,
            "target_by_turn": {t: target_tokens[t] for t in turns},
            "evaluator_per_turn": ev["rubric"] + ev["step_judge"],
            "pre_attack_total": actor_pre["total_input_tokens"],
            "pre_attack_calls": actor_pre["n_calls"],
        }
    ev_per_turn = ev["refusal"] + ev["rubric"]
    if attack == "acronym":
        ev_per_turn += ev["disclaimer"]
    return {
        "attacker_by_turn": {t: attacker_call_tokens(attack, goal, t) for t in turns},
        "target_by_turn": {t: target_tokens[t] for t in turns},
        "evaluator_per_turn": ev_per_turn,
        "pre_attack_total": 0,
        "pre_attack_calls": 0,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", default="results/audit/phase21_cost.json")
    args = parser.parse_args()

    case = load_goal()
    goal, system_prompt = case["task"], case["target_system"]

    ev = evaluator_tokens()
    actor_pre = actor_attack_pre_attack(goal)
    turns_to_sample = [1, 4, 8]

    target_tokens = {
        t: target_call_tokens(system_prompt, t, OUTPUT_TOKENS["target"]["expected"])
        for t in turns_to_sample
    }
    per_attack = {
        a: per_turn_inputs(a, goal, turns_to_sample, target_tokens, ev, actor_pre)
        for a in ("crescendo", "opposite_day", "acronym", "actor_attack")
    }

    measured = {
        "encoding": "o200k_base (gpt-4o)",
        "pricing_usd_per_1m": {
            "input": PRICE_INPUT_PER_1M, "cached_input": PRICE_CACHED_PER_1M,
            "output": PRICE_OUTPUT_PER_1M,
            "source": "https://developers.openai.com/api/docs/pricing "
                      "(verified 2026-11-10)",
        },
        "target_system_prompt_tokens": ntok(system_prompt),
        "evaluator_input_tokens": ev,
        "actor_attack_pre_attack": actor_pre,
        "per_attack": per_attack,
    }

    print("MEASURED INPUT TOKENS (o200k_base)")
    print(f"  target system prompt      {ntok(system_prompt):>6}")
    for k in ("refusal", "disclaimer", "rubric", "step_judge", "rewrite"):
        print(f"  {k:<24} {ev[k]:>6}")
    print(f"  ActorAttack pre-attack    {actor_pre['total_input_tokens']:>6} "
          f"({actor_pre['n_calls']} calls: {actor_pre['input_tokens']})")
    print()
    for attack, data in per_attack.items():
        if "attacker_by_turn" in data:
            print(f"  {attack:<13} attacker in/turn: "
                  + ", ".join(f"t{t}={v}" for t, v in data["attacker_by_turn"].items()))
        else:
            print(f"  {attack:<13} no per-turn attacker call "
                  f"(pre-attack {data['pre_attack_total']} tokens / "
                  f"{data['pre_attack_calls']} calls per goal)")
    print()

    # ---- full-run cost model -------------------------------------------- #
    print("FULL-RUN COST MODEL — paper main evaluation "
          f"({GOALS} goals/attack, K={MAX_TURNS})")
    rows = []
    for attack in PAPER_ATTACKS:
        data = per_attack[attack]
        for band in ("low", "expected", "high"):
            a_out = OUTPUT_TOKENS["attacker"][band]
            t_out = OUTPUT_TOKENS["target"][band]
            rubric_out = OUTPUT_TOKENS["rubric"][band]
            if attack == "actor_attack":
                in_per_dialogue = data["pre_attack_total"] + sum(
                    target_call_tokens(system_prompt, t, t_out)
                    for t in range(1, MAX_TURNS + 1))
                in_per_dialogue += (ev["rubric"] + ev["step_judge"]) * MAX_TURNS
                out_per_dialogue = (
                    3 * a_out                                       # pre-attack
                    + MAX_TURNS * (t_out + rubric_out)
                    + MAX_TURNS * OUTPUT_TOKENS["step_judge"][band]
                )
                rewrite_in = ev["rewrite"] * MAX_TURNS * REWRITE_RATE[band]
                rewrite_out = OUTPUT_TOKENS["rewrite"][band] * MAX_TURNS * REWRITE_RATE[band]
                in_per_dialogue += rewrite_in
                out_per_dialogue += rewrite_out
                calls_per_dialogue = data["pre_attack_calls"] + 3 * MAX_TURNS + \
                    MAX_TURNS * REWRITE_RATE[band]
            else:
                in_per_dialogue = data["pre_attack_total"] + sum(
                    data["attacker_by_turn"][t] for t in turns_to_sample) / len(turns_to_sample) * MAX_TURNS
                in_per_dialogue += sum(
                    target_call_tokens(system_prompt, t, t_out)
                    for t in range(1, MAX_TURNS + 1))
                in_per_dialogue += data["evaluator_per_turn"] * MAX_TURNS
                out_per_dialogue = MAX_TURNS * (
                    a_out + t_out + OUTPUT_TOKENS["refusal"][band] + rubric_out)
                calls_per_dialogue = 4 * MAX_TURNS

            dialogues = GOALS
            total_in = in_per_dialogue * dialogues
            total_out = out_per_dialogue * dialogues
            cost = (total_in / 1e6 * PRICE_INPUT_PER_1M
                    + total_out / 1e6 * PRICE_OUTPUT_PER_1M)
            rows.append({
                "attack": attack, "band": band, "dialogues": dialogues,
                "calls_per_dialogue": round(calls_per_dialogue, 2),
                "input_tokens_per_dialogue": round(in_per_dialogue),
                "output_tokens_per_dialogue": round(out_per_dialogue),
                "total_input_tokens": round(total_in),
                "total_output_tokens": round(total_out),
                "cost_usd": round(cost, 2),
            })
    for row in rows:
        print(f"  {row['attack']:<13} {row['band']:<9} "
              f"calls/dlg={row['calls_per_dialogue']:>5}  "
              f"in={row['total_input_tokens']:>11,}  out={row['total_output_tokens']:>10,}  "
              f"${row['cost_usd']:>9,.2f}")

    totals = {}
    for band in ("low", "expected", "high"):
        subset = [r for r in rows if r["band"] == band]
        totals[band] = {
            "total_input_tokens": sum(r["total_input_tokens"] for r in subset),
            "total_output_tokens": sum(r["total_output_tokens"] for r in subset),
            "cost_usd": round(sum(r["cost_usd"] for r in subset), 2),
            "total_calls": sum(r["calls_per_dialogue"] * r["dialogues"] for r in subset),
        }
        t = totals[band]
        print(f"\n  TOTAL {band:<9} calls={t['total_calls']:>7,.0f}  "
              f"in={t['total_input_tokens']:>11,}  out={t['total_output_tokens']:>10,}  "
              f"${t['cost_usd']:>9,.2f}")

    report = {
        "measured": measured,
        "assumed_output_tokens": OUTPUT_TOKENS,
        "assumed_rewrite_rate": REWRITE_RATE,
        "goals_per_attack": GOALS,
        "max_turns": MAX_TURNS,
        "paper_attacks": list(PAPER_ATTACKS),
        "rows": rows,
        "totals": totals,
    }
    out = Path(args.json)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
